// Test/export validation only. Never upgrades an established native fixture.
import assert from 'node:assert/strict';
import {existsSync,readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import historicalTrimDefaults from './historical-trim-defaults.cjs';
const {withHistoricalTrimDefaults,describeHistoricalTrimDefaults}=historicalTrimDefaults;

const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
export function assertHistoricalNativeFixture(file,expected,message='Historical native fixture differs outside declared missing trim defaults.'){
 const bytes=readFileSync(file),raw=JSON.parse(bytes),document=typeof expected==='string'?JSON.parse(expected):expected;
 assert.deepEqual(withHistoricalTrimDefaults(raw),document,message);
 assert.deepEqual(readFileSync(file),bytes,'Historical native fixture bytes changed during validation.');
 const audit={format:'HistoricalNativeFixtureExpectation/1',status:'validated-json-with-fixed-defaults-source-bytes-unchanged',path:file instanceof URL?fileURLToPath(file):resolve(file),sha256:sha(bytes),bytes:bytes.length,expectationAdapter:describeHistoricalTrimDefaults(raw)};
 console.log(JSON.stringify(audit));return audit;
}
export function preserveHistoricalNativeFixture(file,text,message){
 if(existsSync(file))return assertHistoricalNativeFixture(file,text,message);
 // Explicit new outputs retain their generated bytes; existing files are never rewritten.
 writeFileSync(file,text,{flag:'wx'});
 const bytes=readFileSync(file),audit={format:'HistoricalNativeFixtureExpectation/1',status:'created-exclusive',path:file instanceof URL?fileURLToPath(file):resolve(file),sha256:sha(bytes),bytes:bytes.length};
 console.log(JSON.stringify(audit));return audit;
}
